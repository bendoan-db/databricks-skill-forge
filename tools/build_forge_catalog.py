"""Render forge's Use cases and Resume tables, and MANIFEST.md, from each skill's ucs.yaml and SKILL.md and forge.yaml.

    uv run tools/build_forge_catalog.py           # rewrite the block in skills/forge/SKILL.md, and MANIFEST.md
    uv run tools/build_forge_catalog.py --check   # exit 1 if either is out of date (tests/test_forge.py checks the same)

MANIFEST.md lists forge and every use-case skill in forge.yaml, with its description, inputs, and outputs. The
forge-smith builder isn't a use case, so it isn't listed.

Maintainer tool: it lives outside skills/, so it isn't published with any skill.
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

SKILLS_DIR = Path(__file__).resolve().parents[1] / "skills"
FORGE = SKILLS_DIR / "forge"
MANIFEST = SKILLS_DIR.parent / "MANIFEST.md"
BLOCK_RE = re.compile(r"(?s)(<!-- >>> catalog:[^\n]*-->\n).*?(<!-- <<< catalog -->)")
SKILL_NAME_RE = re.compile(r"(?<![`\w-])(forge-[a-z-]+[a-z])(?![`\w-])")
FIELDS = ("title", "choose_when", "not_for", "produces", "state_file", "next")


def cell(text: str) -> str:
    """One table cell: skill names in backticks, pipes escaped."""
    return SKILL_NAME_RE.sub(r"`\1`", str(text)).replace("|", "\\|")


def load(skills_dir: Path = SKILLS_DIR) -> tuple[dict, list[tuple[dict, dict]]]:
    """forge.yaml, and (use_cases entry, that skill's ucs.yaml) pairs in forge.yaml order."""
    forge = yaml.safe_load((skills_dir / "forge" / "forge.yaml").read_text())
    pairs = []
    for entry in forge["use_cases"]:
        ucs = yaml.safe_load((skills_dir / entry["name"] / "ucs.yaml").read_text())
        if missing := [field for field in FIELDS if field not in (ucs.get("catalog") or {})]:
            raise SystemExit(f"{entry['name']}/ucs.yaml catalog is missing {missing}")
        pairs.append((entry, ucs))
    return forge, pairs


def render(skills_dir: Path = SKILLS_DIR) -> str:
    _, pairs = load(skills_dir)
    lines = [
        "| Use case | Skill (minimum version) | Choose it when the user wants | Not for | Produces | Next step |",
        "|---|---|---|---|---|---|",
    ]
    for entry, ucs in pairs:
        c = ucs["catalog"]
        next_step = ", ".join(f"`{name}`" for name in c["next"]) or "—"
        lines.append(f"| {cell(c['title'])} | `{entry['name']}` ({entry['min_version']}) | {cell(c['choose_when'])} "
                     f"| {cell(c['not_for'])} | {cell(c['produces'])} | {next_step} |")
    lines += ["", "Resume table, checked in this order:", "", "| State file in `<workdir>` | Skill |", "|---|---|"]
    lines += [f"| `{ucs['catalog']['state_file']}` | `{entry['name']}` |" for entry, ucs in pairs]
    return "\n".join(lines) + "\n"


def description(skill_dir: Path) -> str:
    """What the skill does: its frontmatter description, without the routing prefix and the "Use when" sentences."""
    text = (skill_dir / "SKILL.md").read_text()
    meta = yaml.safe_load(re.match(r"^---\n(.*?)\n---", text, re.DOTALL).group(1))
    what = re.sub(r"^Forge use case, normally started by the forge skill:\s*", "", meta["description"])
    what = what.split(" Use when ", 1)[0].strip()
    return what[:1].upper() + what[1:]


def names(items: list[str]) -> str:
    return ", ".join(f"`{name}`" for name in items) or "none"


def render_manifest(skills_dir: Path = SKILLS_DIR) -> str:
    forge, pairs = load(skills_dir)
    router = forge.get("manifest") or {}
    if missing := [key for key in ("title", "inputs", "produces") if not router.get(key)]:
        raise SystemExit(f"skills/forge/forge.yaml manifest is missing {missing}")
    rows = [(f"[`forge`](skills/forge/SKILL.md)<br>{cell(router['title'])}", description(skills_dir / "forge"),
             cell(router["inputs"]), cell(router["produces"]))]
    for entry, ucs in pairs:
        inputs = ucs.get("inputs") or {}
        given = [f"**Required:** {names(inputs.get('required') or [])}"]
        given += [f"**Builds on:** `{dep['name']}`, which it runs first if needed" for dep in ucs.get("requires") or []]
        given += [f"**Optional:** {names(inputs.get('optional') or [])}"]
        c = ucs["catalog"]
        rows.append((f"[`{entry['name']}`](skills/{entry['name']}/SKILL.md)<br>{cell(c['title'])}",
                     description(skills_dir / entry["name"]), "<br>".join(given),
                     f"{cell(c['produces'])}<br>**State file:** `{c['state_file']}`"))
    lines = [
        "# Forge skills",
        "",
        "<!-- Generated by tools/build_forge_catalog.py from each skill's SKILL.md and ucs.yaml, and skills/forge/forge.yaml."
        " Don't edit by hand. -->",
        "",
        "The skills Forge installs, and what each one needs and produces. Start every build with `forge`: it picks the "
        "use case, and that skill asks for its required inputs before it builds anything.",
        "",
        "| Name | Description | Input | Outputs |",
        "|---|---|---|---|",
        *(f"| {name} | {cell(what)} | {given} | {made} |" for name, what, given, made in rows),
    ]
    return "\n".join(lines) + "\n"


def update(text: str, block: str) -> str:
    if len(BLOCK_RE.findall(text)) != 1:
        raise SystemExit("skills/forge/SKILL.md needs exactly one catalog block between its >>> and <<< markers")
    return BLOCK_RE.sub(lambda m: m.group(1) + block + m.group(2), text)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="Exit 1 if SKILL.md is out of date; don't write")
    args = p.parse_args()
    path = FORGE / "SKILL.md"
    outputs = {path: update(path.read_text(), render()), MANIFEST: render_manifest()}
    stale = [target for target, new in outputs.items() if not target.is_file() or target.read_text() != new]
    if args.check:
        if stale:
            sys.exit(f"{', '.join(str(s.relative_to(SKILLS_DIR.parent)) for s in stale)} out of date: "
                     "run `uv run tools/build_forge_catalog.py`")
        print("catalog up to date")
        return
    for target in stale:
        target.write_text(outputs[target])
        print(f"updated {target}")
    if not stale:
        print("catalog up to date")


if __name__ == "__main__":
    main()
